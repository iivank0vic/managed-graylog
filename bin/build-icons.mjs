// Dev tool: extracts selected Lucide icons (ISC license) into includes/icons.php.
// Usage: node bin/build-icons.mjs /path/to/node_modules/lucide-static/icons
import fs from 'node:fs';
const dir = process.argv[2];
const names = ['rocket','network','shield-check','arrow-right-left','wrench','compass','arrow-right','arrow-up-right','layers','shopping-cart','gamepad-2','boxes','building-2','users','shield','globe','terminal','server','hard-drive','database','cloud','lock','activity','archive','gauge','code','check','x','triangle-alert','git-branch','cpu','file-text','search','bell','key-round','refresh-cw','plus','minus','chevron-down','mail','clock','life-buoy','workflow','scale','history','radar','cable','box','file-code','list-checks','message-square','circle-check','circle-alert','info','hard-drive-download','split','timer','scan-search','siren','disc-3','copy'];
let out = [];
for (const n of names) {
  const f = `${dir}/${n}.svg`;
  if (!fs.existsSync(f)) { console.error('missing', n); continue; }
  const svg = fs.readFileSync(f, 'utf8');
  const inner = svg.replace(/<!--.*?-->/s,'').replace(/^[\s\S]*?<svg[^>]*>/,'').replace(/<\/svg>\s*$/,'').replace(/\s*\n\s*/g,'').trim();
  out.push(`    '${n}' => '${inner.replace(/'/g,"\\'")}',`);
}
const php = `<?php
/**
 * Inline SVG icons. Paths from Lucide (https://lucide.dev), ISC License,
 * Copyright (c) Lucide Icons and Contributors. Generated by bin/build-icons.mjs.
 */
declare(strict_types=1);

function icon_paths(): array
{
    static $icons = [
${out.join('\n')}
    ];
    return $icons;
}

/** Decorative inline icon (aria-hidden). Pass a label via surrounding text instead. */
function icon(string $name, string $class = ''): string
{
    $paths = icon_paths()[$name] ?? '';
    $cls = 'icon' . ($class !== '' ? ' ' . $class : '');
    return '<svg class="' . htmlspecialchars($cls, ENT_QUOTES) . '" viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' . $paths . '</svg>';
}

/** Brand mark: stacked log lines inside a frame. Original artwork. */
function brand_mark(): string
{
    static $n = 0;
    $id = 'bm-g' . (++$n);
    return str_replace('bm-g', $id, '<svg class="brand__mark" viewBox="0 0 32 32" width="28" height="28" aria-hidden="true" focusable="false">'
        . '<defs><linearGradient id="bm-g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#5eead4"/><stop offset=".55" stop-color="#38bdf8"/><stop offset="1" stop-color="#818cf8"/></linearGradient></defs>'
        . '<rect x="1.5" y="1.5" width="29" height="29" rx="7" fill="#0b1018" stroke="url(#bm-g)" stroke-width="1.5"/>'
        . '<rect x="8" y="9" width="16" height="2.6" rx="1.3" fill="url(#bm-g)"/>'
        . '<rect x="8" y="14.7" width="11" height="2.6" rx="1.3" fill="url(#bm-g)" opacity=".85"/>'
        . '<rect x="8" y="20.4" width="6" height="2.6" rx="1.3" fill="url(#bm-g)" opacity=".7"/>'
        . '<circle cx="22.5" cy="21.7" r="1.6" fill="#5eead4"/>'
        . '</svg>');
}
`;
fs.writeFileSync(new URL('../includes/icons.php', import.meta.url), php);
console.log('wrote', out.length);
